export const TEMPLATE_ID = 'tier-a-npm-pack-no-build-v1';

// A safe intra-package relative path: one or more `/`-joined segments of
// [A-Za-z0-9._-]. No leading slash, no whitespace, no shell metacharacters,
// and (critically) no newlines — these values are interpolated into the
// generated build/smoke shell scripts, so anything outside this set could
// inject commands. `..` traversal is additionally rejected by the validator.
export const SAFE_REL_PATH_RE = /^[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*$/;

export const PARAM_SPEC = {
  package_name:         { type: 'string',  required: true,  maxLength: 214 },
  package_version:      { type: 'string',  required: true,  maxLength: 256 },
  description:          { type: 'string',  required: true,  maxLength: 500 },
  source_url:           { type: 'string',  required: true,  maxLength: 500 },
  source_ref:           { type: 'string',  required: true,  maxLength: 40, minLength: 40 },
  source_tag:           { type: 'string',  required: true,  maxLength: 100 },
  upstream_npm_version: { type: 'string',  required: true,  maxLength: 256 },
  has_cli:              { type: 'boolean', required: true },
  cli_bin_path:         { type: 'string',  required: false, maxLength: 200, pattern: SAFE_REL_PATH_RE },
  main_entry:           { type: 'string',  required: true,  maxLength: 200, pattern: SAFE_REL_PATH_RE },
};

export function generateManifest(p) {
  const manifest = {
    name: p.package_name.value,
    version: p.package_version.value,
    description: p.description.value,
    native_tier: 'A',
    source: {
      url: p.source_url.value,
      ref: p.source_ref.value,
      ref_type: 'commit',
    },
    upstream_npm: {
      version: p.upstream_npm_version.value,
    },
    entrypoint: 'build.entrypoint.sh',
    smoke: 'verify.smoke.sh',
    outputs: [
      {
        id: 'main',
        type: 'npm-package',
        path: `out/${p.package_name.value}-${p.package_version.value}.tgz`,
        pulp_name: p.package_name.value,
      },
    ],
  };
  return JSON.stringify(manifest, null, 2) + '\n';
}

export function generateBuildEntrypoint(p) {
  const memberChecks = [`assert_tgz_has_member "\${main_tgz}" package/package.json`];
  memberChecks.push(`assert_tgz_has_member "\${main_tgz}" package/${p.main_entry.value}`);
  if (p.has_cli.value && p.cli_bin_path?.value) {
    memberChecks.push(`assert_tgz_has_member "\${main_tgz}" package/${p.cli_bin_path.value}`);
  }

  return `#!/usr/bin/env bash
# Tier A factory build: \${PACKAGE_NAME} from git source via npm pack (local checkout only).
# Writes only to OUT_DIR; must not publish.
# Generated by tier-a-npm-pack-no-build-v1 template — do not edit.
set -euo pipefail

: "\${MANIFEST_PATH:?MANIFEST_PATH required}"
: "\${OUT_DIR:?OUT_DIR required}"
: "\${WORK_DIR:?WORK_DIR required}"

PACKAGE_NAME="$(jq -r .name "\${MANIFEST_PATH}")"
VERSION="$(jq -r .version "\${MANIFEST_PATH}")"
SOURCE_URL="$(jq -r .source.url "\${MANIFEST_PATH}")"
SOURCE_REF="$(jq -r .source.ref "\${MANIFEST_PATH}")"
MAIN_TGZ_REL="$(jq -r '.outputs[] | select(.type == "npm-package") | .path' "\${MANIFEST_PATH}")"
main_tgz="\${OUT_DIR}/\${MAIN_TGZ_REL#out/}"

assert_tgz_has_member() {
    local tgz="$1" member="$2"
    tar -xOf "\${tgz}" "\${member}" >/dev/null 2>&1 || {
        echo "[build.entrypoint] \${tgz} missing \${member}" >&2
        echo "Tarball listing:" >&2
        tar tf "\${tgz}" >&2 || file "\${tgz}" >&2 || true
        exit 1
    }
}

SRC="\${WORK_DIR}/\${PACKAGE_NAME}-src"
rm -rf "\${SRC}"
mkdir -p "\${OUT_DIR}" "$(dirname "\${main_tgz}")"

echo "[build.entrypoint] Cloning \${SOURCE_URL} @ \${SOURCE_REF}"
git clone --no-checkout "\${SOURCE_URL}" "\${SRC}"

cd "\${SRC}"
git checkout "\${SOURCE_REF}"

actual_sha="$(git rev-parse HEAD)"
[[ "\${actual_sha}" == "\${SOURCE_REF}" ]] || {
    echo "Source commit \${actual_sha} != expected \${SOURCE_REF}" >&2
    exit 1
}

echo "[build.entrypoint] Packing from git checkout (npm pack)"
rm -f "\${main_tgz}"
packed="$(npm pack --quiet --ignore-scripts)"
mv "\${packed}" "\${main_tgz}"

[[ -f "\${main_tgz}" ]] || {
    echo "Expected tarball: \${main_tgz}" >&2
    exit 1
}

${memberChecks.join('\n')}

packed_version="$(tar -xOf "\${main_tgz}" package/package.json | jq -r .version)"
[[ "\${packed_version}" == "\${VERSION}" ]] || {
    echo "Packed version \${packed_version} != manifest \${VERSION}" >&2
    exit 1
}

echo "[build.entrypoint] Output: \${main_tgz}"
`;
}

export function generateVerifySmoke(p) {
  let cliTest = '';
  if (p.has_cli.value && p.cli_bin_path?.value) {
    const binName = p.cli_bin_path.value.split('/').pop().replace(/\.js$/, '');
    cliTest = `
echo "[verify.smoke] Testing CLI"
"\${tmpdir}/node_modules/.bin/${binName}" --help >/dev/null 2>&1 || {
    echo "CLI ${binName} failed basic --help check" >&2
    exit 1
}`;
  }

  return `#!/usr/bin/env bash
# Post-build smoke checks for Tier A output.
# Generated by tier-a-npm-pack-no-build-v1 template — do not edit.
set -euo pipefail

: "\${MANIFEST_PATH:?MANIFEST_PATH required}"
: "\${OUT_DIR:?OUT_DIR required}"

PACKAGE_NAME="$(jq -r .name "\${MANIFEST_PATH}")"
VERSION="$(jq -r .version "\${MANIFEST_PATH}")"
MAIN_TGZ="$(jq -r '.outputs[] | select(.type == "npm-package") | .path' "\${MANIFEST_PATH}")"

path_under_out() {
    local rel="$1"
    echo "\${OUT_DIR}/\${rel#out/}"
}

MAIN_PATH="$(path_under_out "\${MAIN_TGZ}")"

echo "[verify.smoke] OUT_DIR=\${OUT_DIR}" >&2
echo "[verify.smoke] MAIN_PATH=\${MAIN_PATH}" >&2

[[ -f "\${MAIN_PATH}" ]] || {
    echo "Missing tarball: \${MAIN_PATH}" >&2
    exit 1
}

tgz_has_member() {
    local tgz="$1" member="$2"
    tar -xOf "\${tgz}" "\${member}" >/dev/null 2>&1
}

for member in package/package.json package/${p.main_entry.value}; do
    tgz_has_member "\${MAIN_PATH}" "\${member}" || {
        echo "Main tarball missing \${member}" >&2
        exit 1
    }
done

packed_name="$(tar -xOf "\${MAIN_PATH}" package/package.json | jq -r .name)"
packed_version="$(tar -xOf "\${MAIN_PATH}" package/package.json | jq -r .version)"
[[ "\${packed_name}" == "\${PACKAGE_NAME}" ]] || {
    echo "Unexpected package name: \${packed_name}" >&2
    exit 1
}
[[ "\${packed_version}" == "\${VERSION}" ]] || {
    echo "Unexpected package version: \${packed_version}" >&2
    exit 1
}

tmpdir="$(mktemp -d)"
trap 'rm -rf "\${tmpdir}"' EXIT

npm install --ignore-scripts --no-audit --no-fund --prefix "\${tmpdir}" "\${MAIN_PATH}"

echo "[verify.smoke] Testing module require"
node -e "require(process.argv[1])" "\${tmpdir}/node_modules/\${PACKAGE_NAME}"
${cliTest}

echo "[verify.smoke] OK"
`;
}

export function generateEvidence(p, evidence, couldNotVerify) {
  const lines = [
    `Package identity: ${p.package_name.value}@${p.package_version.value}`,
    `Native tier: A`,
    '',
    `Source repository: ${p.source_url.value.replace(/\.git$/, '')}`,
    `Version tag: ${p.source_tag.value}`,
    `Pinned commit: ${p.source_ref.value}`,
    '',
  ];

  if (evidence && evidence.length > 0) {
    lines.push('Evidence:');
    for (const e of evidence) {
      lines.push(`- [${e.kind}] ${e.detail}`);
    }
    lines.push('');
  }

  if (couldNotVerify && couldNotVerify.length > 0) {
    lines.push('Could not verify:');
    for (const item of couldNotVerify) {
      lines.push(`- ${item}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
